import { describe, expect, it } from 'vitest';

import { formatSalaryDisplay } from '@/services/salaryFormat';

describe('formatSalaryDisplay', () => {
  it.each([
    ['연봉 5,000만원 이상', '연 5,000만 원 이상'],
    ['연 4,500만원 ~ 6,000만원', '연 4,500만 원 ~ 6,000만 원'],
    ['월 750만원 ~ 1,100만원', '월 750만 원 ~ 1,100만 원'],
    ['월 800만-1000만', '월 800만 원 ~ 1,000만 원'],
    ['월급 3,500,000원', '월 350만 원'],
    ['월급 3,500,000원~4,000,000원', '월 350만 원 ~ 400만 원'],
    ['연봉 4500~6000만원', '연 4,500만 원 ~ 6,000만 원'],
    ['연봉 50,000,000원', '연 5,000만 원'],
    ['연봉 연봉 5,000만원', '연 5,000만 원'],
    ['연봉 3,000만원~연봉 4,000만원', '연 3,000만 원 ~ 4,000만 원'],
    ['연간 5,000만원', '연 5,000만 원'],
    ['월간 350만원', '월 350만 원'],
    ['월 350.5만원', '월 350.5만 원'],
    ['연봉26,000,000원 이상 ~ 27,000,000원 이하,', '연 2,600만 원 이상 ~ 2,700만 원 이하'],
    [
      '연봉36,000,000원 이상 ~ 40,000,000원 이하, 면접 후 재조정 가능',
      '연 3,600만 원 이상 ~ 4,000만 원 이하, 면접 후 재조정 가능',
    ],
    ['시급10,320원 이상,', '시급 10,320원 이상'],
    ['일급100,000원 이상 ~ 100,000원 이하,', '일급 10만 원 이상 ~ 10만 원 이하'],
    [
      '월급1,604,360원 이상 ~ 1,654,360원 이하, 면접 후 재조정 가능',
      '월 160.436만 원 이상 ~ 165.436만 원 이하, 면접 후 재조정 가능',
    ],
    [
      '연봉40,000,000원 이상 ~ 45,000,000원 이하, 면접 후 재조정 가능',
      '연 4,000만 원 이상 ~ 4,500만 원 이하, 면접 후 재조정 가능',
    ],
    [
      '월급2,156,880원 이상 ~ 2,156,880원 이하, 상여금 : 10(미 포함) ,',
      '월 215.688만 원 이상 ~ 215.688만 원 이하, 상여금 : 10(미 포함)',
    ],
    ['월 400만원 (주 20시간 시간제)', '월 400만 원 (주 20시간 시간제)'],
    ['300~400만원', '300만 원 ~ 400만 원'],
    ['공공기관 호봉제/내규', '공공기관 호봉제/내규'],
  ])('%s의 급여 주기·숫자·단위를 표준화한다', (input, expected) => {
    expect(formatSalaryDisplay(input)).toBe(expected);
  });

  it('최소 연봉과 협의 조건을 의미 손실 없이 정리한다', () => {
    expect(formatSalaryDisplay('최소연봉 / 3000만원 - 면접 후 협의가능')).toBe(
      '연 3,000만 원 이상 (면접 후 협의 가능)',
    );
    expect(formatSalaryDisplay('최소연봉 / 2600만원')).toBe('연 2,600만 원 이상');
    expect(formatSalaryDisplay('최소연봉 / 3000만원 - 상여금 별도')).toBe(
      '연 3,000만 원 이상 - 상여금 별도',
    );
  });

  it('원 단위 급여는 반올림 없이 정확한 소수 만 원 단위로 보존한다', () => {
    expect(formatSalaryDisplay('월급 2,096,271원 이상')).toBe('월 209.6271만 원 이상');
  });

  it.each([
    ['월급 9,999원', '월 9,999원'],
    ['월급 10,000원', '월 1만 원'],
    ['월급 10,001원', '월 1.0001만 원'],
    ['월급 10,010원', '월 1.001만 원'],
    ['월급 12,300원', '월 1.23만 원'],
    ['연봉 90,071,992,547,409,931원', '연 9,007,199,254,740.9931만 원'],
    ['시급 100,000원', '시급 100,000원'],
    ['100,000원', '100,000원'],
  ])('만 원 변환 경계와 시급·무주기 예외를 정확히 처리한다: %s', (input, expected) => {
    expect(formatSalaryDisplay(input)).toBe(expected);
  });

  it('표준화된 값을 다시 처리해도 표시가 바뀌지 않는다', () => {
    [
      '연 4,500만 원 ~ 6,000만 원',
      '월 350만 원',
      '월 209.6271만 원 이상',
      '연 5,000만 원 이상',
    ].forEach((salary) => expect(formatSalaryDisplay(formatSalaryDisplay(salary))).toBe(salary));
  });

  it.each([
    ['시급 10,030원', '시급 10,030원'],
    ['시급 10,000원', '시급 10,000원'],
    ['일급 150,000원', '일급 15만 원'],
    ['회사 내규에 따름', '회사 내규에 따름'],
    ['협의/미등록', '협의/미등록'],
    ['', ''],
    [undefined, ''],
  ])('정확한 금액과 비정형 안내를 안전하게 보존한다', (input, expected) => {
    expect(formatSalaryDisplay(input)).toBe(expected);
  });
});
